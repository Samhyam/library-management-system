from playwright.sync_api import sync_playwright
S='docs/screenshots/'
fails=[]
def check(name, cond):
    print(('PASS ' if cond else 'FAIL ')+name)
    if not cond: fails.append(name)

with sync_playwright() as p:
    b = p.chromium.launch(); pg = b.new_page(viewport={'width':1280,'height':800})
    errs=[]
    pg.on('pageerror', lambda e: errs.append(str(e)))
    pg.on('console', lambda m: errs.append(m.text) if m.type=='error' and '4' not in m.text[:0] else None)
    pg.goto('http://localhost:3111/'); pg.wait_for_selector('.stat')
    check('E01 dashboard shows 6 stat cards', pg.locator('.stat').count()==6)
    check('E01 dashboard total books = 10', pg.locator('.stat b').first.inner_text()=='10')
    pg.screenshot(path=S+'01-dashboard.png')

    pg.click('#nav a[data-view=books]'); pg.wait_for_selector('#bookRows tr strong'); pg.wait_for_timeout(500)
    check('E02 books list shows 10 rows', pg.locator('#bookRows tr').count()==10)
    pg.screenshot(path=S+'02-book-list.png')

    pg.fill('#bookSearch','silber'); pg.wait_for_timeout(600)
    check('E03 search "silber" returns 2 books', pg.locator('#bookRows tr').count()==2)
    pg.fill('#bookSearch',''); pg.wait_for_timeout(600)
    pg.select_option('#bookAvail','false'); pg.wait_for_timeout(400)
    check('E04 filter On loan returns 3 books', pg.locator('#bookRows tr').count()==3)
    pg.select_option('#bookAvail',''); pg.wait_for_timeout(400)

    pg.click('#addBook'); pg.click('#bookForm button[type=submit]')
    check('E05 empty add-book form shows client validation errors', pg.locator('#bookForm .err:not(:empty)').count()>=4)
    pg.screenshot(path=S+'03-add-book-validation.png')
    pg.fill('#bookForm [name=title]','Deep Work'); pg.fill('#bookForm [name=author]','Cal Newport')
    pg.fill('#bookForm [name=isbn]','978-0-13-235088-4'); pg.fill('#bookForm [name=category]','Self-Help'); pg.fill('#bookForm [name=publicationYear]','2016')
    pg.click('#bookForm button[type=submit]'); pg.wait_for_timeout(400)
    check('E06 duplicate ISBN shows server error on ISBN field', 'already registered' in pg.locator('#bookForm [data-err=isbn]').inner_text())
    pg.screenshot(path=S+'04-duplicate-isbn.png')
    pg.fill('#bookForm [name=isbn]','978-1-4555-8669-1')
    pg.click('#bookForm button[type=submit]'); pg.wait_for_timeout(500)
    check('E07 new book appears in list', pg.locator('#bookRows tr', has_text='Deep Work').count()==1)
    check('E07 toast confirms add', 'Book added' in pg.locator('#toast').inner_text())
    pg.screenshot(path=S+'05-book-added.png')

    row = pg.locator('#bookRows tr', has_text='Deep Work')
    row.get_by_role('button', name='Edit').click(); pg.wait_for_timeout(300)
    check('E08 edit dialog is pre-filled', pg.input_value('#bookForm [name=title]')=='Deep Work')
    pg.fill('#bookForm [name=title]','Deep Work (2nd printing)')
    pg.screenshot(path=S+'06-edit-book.png')
    pg.click('#bookForm button[type=submit]'); pg.wait_for_timeout(500)
    check('E08 edited title shown', pg.locator('#bookRows tr', has_text='2nd printing').count()==1)

    pg.locator('#bookRows tr', has_text='2nd printing').get_by_role('button', name='Delete').click(); pg.wait_for_timeout(300)
    pg.screenshot(path=S+'07-delete-confirm.png')
    pg.click('#confirmOk'); pg.wait_for_timeout(500)
    check('E09 deleted book removed from list', pg.locator('#bookRows tr', has_text='2nd printing').count()==0)

    pg.locator('#bookRows tr', has_text='Sapiens').get_by_role('button', name='Delete').click(); pg.wait_for_timeout(300)
    pg.click('#confirmOk'); pg.wait_for_timeout(400)
    check('E10 deleting a book on loan shows error in dialog', 'on loan' in pg.locator('#confirmForm [data-err=_form]').inner_text())
    pg.screenshot(path=S+'08-delete-blocked.png'); pg.click('#confirmDialog [data-close]')

    pg.click('#nav a[data-view=members]'); pg.wait_for_selector('#memberRows tr strong')
    check('E11 members list shows 6 rows', pg.locator('#memberRows tr').count()==6)
    pg.screenshot(path=S+'09-member-list.png')
    pg.click('#addMember'); pg.fill('#memberForm [name=name]','Meera Das'); pg.fill('#memberForm [name=email]','bad-email'); pg.fill('#memberForm [name=phone]','123')
    pg.click('#memberForm button[type=submit]')
    check('E12 invalid member shows email and phone errors', pg.locator('#memberForm .err:not(:empty)').count()==2)
    pg.screenshot(path=S+'10-add-member-validation.png')
    pg.fill('#memberForm [name=email]','meera.das@example.com'); pg.fill('#memberForm [name=phone]','9812345678')
    pg.click('#memberForm button[type=submit]'); pg.wait_for_timeout(500)
    check('E13 new member appears', pg.locator('#memberRows tr', has_text='Meera Das').count()==1)
    pg.fill('#memberSearch','meera'); pg.wait_for_timeout(600)
    check('E14 member search works', pg.locator('#memberRows tr').count()==1)
    pg.screenshot(path=S+'11-member-added.png'); pg.fill('#memberSearch','')

    pg.click('#nav a[data-view=borrowings]'); pg.wait_for_selector('#loanRows tr strong'); pg.wait_for_timeout(500)
    check('E15 borrowings list shows 6 records', pg.locator('#loanRows tr').count()==6)
    check('E15 overdue pill is shown', pg.locator('#loanRows .pill.overdue').count()>=1)
    pg.screenshot(path=S+'12-borrowing-list.png')
    pg.select_option('#loanFilter','overdue'); pg.wait_for_timeout(400)
    check('E16 overdue filter shows overdue loans only', pg.locator('#loanRows tr').count()>=1 and pg.locator('#loanRows .pill:not(.overdue)').count()==0)
    pg.screenshot(path=S+'13-overdue-filter.png'); pg.select_option('#loanFilter','')

    pg.click('#issueBtn'); pg.wait_for_timeout(400)
    pg.click('#issueForm button[type=submit]')
    check('E17 issue without selection shows errors', pg.locator('#issueForm .err:not(:empty)').count()==2)
    pg.select_option('#issueForm [name=bookId]', label='Atomic Habits (James Clear)')
    pg.select_option('#issueForm [name=memberId]', label='Meera Das')
    pg.screenshot(path=S+'14-issue-book.png')
    pg.click('#issueForm button[type=submit]'); pg.wait_for_timeout(600)
    check('E18 issued loan appears as Borrowed', pg.locator('#loanRows tr', has_text='Meera Das').locator('.pill.borrowed').count()==1)
    pg.screenshot(path=S+'15-book-issued.png')

    pg.click('#nav a[data-view=books]'); pg.wait_for_selector('#bookRows tr strong'); pg.wait_for_timeout(500)
    check('E19 issued book now shows On loan on Books page', pg.locator('#bookRows tr', has_text='Atomic Habits').locator('.pill.loan').count()==1)
    pg.click('#nav a[data-view=borrowings]'); pg.wait_for_selector('#loanRows tr strong'); pg.wait_for_timeout(500)
    pg.locator('#loanRows tr', has_text='Meera Das').get_by_role('button', name='Extend').click(); pg.wait_for_timeout(300)
    pg.screenshot(path=S+'16-extend-due-date.png')
    pg.click('#dueDialog [data-close]')
    pg.locator('#loanRows tr', has_text='Meera Das').get_by_role('button', name='Return').click(); pg.wait_for_timeout(300)
    pg.screenshot(path=S+'17-return-confirm.png')
    pg.click('#confirmOk'); pg.wait_for_timeout(600)
    check('E20 returned loan shows Returned', pg.locator('#loanRows tr', has_text='Atomic Habits').first.locator('.pill.returned').count()==1 and pg.locator('#loanRows tr', has_text='Meera Das').locator('.pill.returned').count()==1)
    pg.screenshot(path=S+'18-book-returned.png')
    pg.click('#nav a[data-view=books]'); pg.wait_for_selector('#bookRows tr strong'); pg.wait_for_timeout(500)
    check('E21 returned book is Available again', pg.locator('#bookRows tr', has_text='Atomic Habits').locator('.pill.ok').count()==1)

    pg.click('#nav a[data-view=dashboard]'); pg.wait_for_selector('.stat'); pg.wait_for_timeout(300)
    check('E22 dashboard counts: 7 available, 3 active', pg.locator('.stat b').nth(1).inner_text()=='7' and pg.locator('.stat b').nth(4).inner_text()=='3')
    pg.screenshot(path=S+'19-dashboard-final.png')

    pg.set_viewport_size({'width':390,'height':800}); pg.click('#nav a[data-view=books]'); pg.wait_for_timeout(400)
    check('E23 no horizontal page scroll on mobile', pg.evaluate('document.documentElement.scrollWidth<=document.documentElement.clientWidth'))
    pg.screenshot(path=S+'20-mobile-books.png')
    check('E24 no JavaScript errors (expected 409 responses ignored)', len([e for e in errs if 'Failed to load resource' not in e])==0)
    print('console errors:', errs)
    b.close()
print('FAILED:', fails)
